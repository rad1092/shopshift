@pytest.mark.parametrize("phase", ["before_backup_replace", "before_project_replace", "after_project_replace"])
def test_process_interruption_never_leaves_truncated_main_or_backup(tmp_path, phase):
    path = tmp_path / "plan.shopshift"
    project = import_project()
    project.name = "version one"
    save_project(project, path)
    project.name = "version two"
    project.mappings["__last__"] = dict(MAPPING, __duration_unit="minutes")
    save_project(project, path)
    # os._exit bypasses Python finally blocks exactly as abrupt process death
    # does. Faults occur on both sides of the atomic file-replacement boundary.
    script = '''
import os, sys
from pathlib import Path
from shopshift import storage
path, phase = Path(sys.argv[1]), sys.argv[2]
project = storage.load_project(path)
project.name = "version three"
replace = storage.os.replace
def abrupt(source, destination):
    destination = Path(destination)
    if phase == "before_backup_replace" and destination == Path(str(path) + ".bak"):
        os._exit(91)
    if phase == "before_project_replace" and destination == path:
        os._exit(91)
    replace(source, destination)
    if phase == "after_project_replace" and destination == path:
        os._exit(91)
storage.os.replace = abrupt
storage.save_project(project, path)
'''
    environment = dict(os.environ, PYTHONPATH=str(Path(__file__).resolve().parents[1] / "src"))
    process = subprocess.run([sys.executable, "-c", script, str(path), phase], env=environment,
                             capture_output=True, text=True, timeout=15)
    assert process.returncode == 91, (process.stdout, process.stderr)
    assert load_project(path).name == ("version three" if phase == "after_project_replace" else "version two")
    assert load_project(path).mappings["__last__"] == dict(MAPPING, __duration_unit="minutes")
    backup = load_project(str(path) + ".bak")
    assert backup.name == ("version one" if phase == "before_backup_replace" else "version two")


def test_corrupt_main_requires_explicit_restore_and_preserves_damaged_bytes(tmp_path):
    path = tmp_path / "plan.shopshift"
    project = import_project()
    project.name = "Known good"
    save_project(project, path)
    project.name = "Next plan"
    save_project(project, path)
    backup_path = Path(str(path) + ".bak")
    good_backup = backup_path.read_bytes()
    damaged = b'{"format":"shopshift","version":1,"project":'
    path.write_bytes(damaged)
    with pytest.raises(StorageProblem):
        load_project(path)
    with pytest.raises(StorageProblem):
        save_project(project, path)
    assert path.read_bytes() == damaged and backup_path.read_bytes() == good_backup
    restored = restore_project(backup_path, path)
    assert restored.name == "Known good" and load_project(path).name == "Known good"
    assert Path(str(path) + ".corrupt").read_bytes() == damaged


