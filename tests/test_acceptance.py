"""Independent acceptance tests: enumerate tiny schedules, not solver internals.

The oracle below deliberately does not call ShopShift's validator or OR-Tools.
It checks elapsed UTC time and pairwise occupancy directly, including every
integer start in each small horizon. Large benchmark fixtures are generated by
scripts/benchmark_shop.py instead of checked into the repository.
"""

