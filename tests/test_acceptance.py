def independent_feasible(project, starts, respect_locks=False):
    """Small oracle for well-formed inputs, independent of production helpers."""
    if set(starts) != set(project.operations):
        return False
    for identity, op in project.operations.items():
        start, end = starts[identity], starts[identity] + op.setup + op.run
        if start < project.horizon_start or end > project.horizon_end:
            return False
        if op.release is not None and start < op.release:
            return False
        for resource in [project.machines[op.machine]] + (
            [project.operators[op.operator]] if op.operator else []
        ):
            # Test inputs use disjoint, nonadjacent windows so containment is
            # unambiguous and independent of calendar normalization policy.
            if not any(window.start <= start and end <= window.end for window in resource.windows):
                return False
        for predecessor in op.predecessors:
            pred = project.operations[predecessor]
            if start < starts[predecessor] + pred.setup + pred.run:
                return False
        existing = project.scenario.placements.get(identity)
        if respect_locks and existing and existing.locked and start != existing.start:
            return False
    for left, right in itertools.combinations(project.operations.values(), 2):
        if left.machine == right.machine or (left.operator and left.operator == right.operator):
            left_end = starts[left.id] + left.setup + left.run
            right_end = starts[right.id] + right.setup + right.run
            if starts[left.id] < right_end and starts[right.id] < left_end:
                return False
    return True


def objective(project, starts):
    ends = {key: starts[key] + op.setup + op.run for key, op in project.operations.items()}
    return max(ends.values()) - project.horizon_start + sum(
        max(0, ends[key] - op.due) for key, op in project.operations.items() if op.due is not None
    )


def all_starts(project):
    ids = tuple(project.operations)
    for values in itertools.product(range(project.horizon_start, project.horizon_end + 1), repeat=len(ids)):
        yield dict(zip(ids, values, strict=True))


def tiny_shop(seed):
    rng = random.Random(seed)
    windows = [[Window(0, 6)], [Window(0, 2), Window(3, 6)], [Window(1, 6)]]
    project = Project(horizon_start=0, horizon_end=6)
    project.machines = {f"m{i}": Resource(f"m{i}", copy.deepcopy(rng.choice(windows))) for i in range(2)}
    project.operators = {"o0": Resource("o0", copy.deepcopy(rng.choice(windows)))}
    for index in range(3):
        key = f"op{index}"
        project.operations[key] = Operation(
            key, "job", f"m{rng.randrange(2)}", "o0" if rng.random() < 0.5 else "",
            setup=1 if rng.random() < 0.3 else 0, run=rng.randint(1, 2),
            predecessors=[f"op{index - 1}"] if index and rng.random() < 0.45 else [],
            release=rng.choice([None, 0, 1]), due=rng.choice([None, 3, 5]),
        )
    return project


@pytest.mark.parametrize("seed", range(16))
def test_validator_agrees_with_exhaustive_independent_oracle(seed):
    project = tiny_shop(seed)
    for starts in all_starts(project):
        scenario = Scenario("Candidate", {key: Placement(value) for key, value in starts.items()})
        actual = not any(issue.severity == "error" for issue in validate(project, scenario))
        assert actual == independent_feasible(project, starts), (seed, starts, validate(project, scenario))


@pytest.mark.parametrize("seed", range(24))
def test_solver_feasibility_and_objective_match_exhaustive_oracle(seed):
    project = tiny_shop(seed)
    if seed % 3 == 0:
        project.scenario.placements["op0"] = Placement(seed % 5, locked=True)
    before = copy.deepcopy(project.to_dict())
    admissible = [starts for starts in all_starts(project) if independent_feasible(project, starts, True)]
    result = suggest(project, time_limit=1)
    assert project.to_dict() == before, "Suggestions must not mutate the project"
    if not admissible:
        assert result.status in {"infeasible", "invalid"}, (seed, result)
        assert not result.placements
    else:
        assert result.status == "optimal", (seed, result)
        starts = {key: value.start for key, value in result.placements.items()}
        assert independent_feasible(project, starts, True)
        expected = min(objective(project, candidate) for candidate in admissible)
        assert objective(project, starts) == expected, (seed, expected, result)
        assert result.objective == pytest.approx(expected)
        for key, placement in project.scenario.placements.items():
            if placement.locked:
                assert result.placements[key] == placement


def test_operator_calendar_and_resource_overlap_are_independent_of_machine():
    project = Project(horizon_start=0, horizon_end=12)
    project.machines = {key: Resource(key, [Window(0, 12)]) for key in ("lathe", "mill")}
    project.operators = {"operator": Resource("operator", [Window(0, 5), Window(7, 12)])}
    project.operations = {
        "a": Operation("a", "A", "lathe", "operator", run=4),
        "b": Operation("b", "B", "mill", "operator", run=4),
    }
    for starts, expected in [({"a": 0, "b": 7}, True), ({"a": 0, "b": 3}, False),
                             ({"a": 2, "b": 7}, False), ({"a": 0, "b": 8}, True)]:
        scenario = Scenario("Candidate", {key: Placement(value) for key, value in starts.items()})
        assert independent_feasible(project, starts) == expected
        assert (not any(i.severity == "error" for i in validate(project, scenario))) == expected


def test_unlocked_bad_schedule_can_be_rebuilt_but_locked_conflict_cannot():
    project = Project(horizon_start=0, horizon_end=10,
                      machines={"m": Resource("m", [Window(0, 10)])}, operations={
                          "a": Operation("a", "J", "m", run=4),
                          "b": Operation("b", "J", "m", run=4),
                      })
    project.scenario.placements = {"a": Placement(-2), "b": Placement(0)}
    result = suggest(project, time_limit=1)
    assert result.status == "optimal"
    assert independent_feasible(project, {key: value.start for key, value in result.placements.items()})
    project.scenario.placements = {"a": Placement(0, True), "b": Placement(1, True)}
    result = suggest(project, time_limit=1)
    assert result.status in {"invalid", "infeasible"}
    assert not result.placements
    assert result.issues


@pytest.mark.parametrize("mutation", ["missing_machine", "missing_operator", "missing_predecessor", "cycle"])
def test_partial_or_invalid_inputs_never_produce_commit_ready_suggestion(mutation):
    project = tiny_shop(2)
    if mutation == "missing_machine":
        project.operations["op0"].machine = "unknown"
    elif mutation == "missing_operator":
        project.operations["op0"].operator = "unknown"
    elif mutation == "missing_predecessor":
        project.operations["op0"].predecessors = ["unknown"]
    else:
        project.operations["op0"].predecessors = ["op2"]
        project.operations["op2"].predecessors = ["op0"]
    result = suggest(project, time_limit=1)
    assert result.status == "invalid"
    assert result.issues and not result.placements


def test_actual_time_limited_search_does_not_claim_infeasibility():
    project = Project(horizon_start=0, horizon_end=1000,
                      machines={"m": Resource("m", [Window(0, 1000)])})
    project.operations = {str(i): Operation(str(i), "J", "m", run=10) for i in range(30)}
    # The arithmetic witness proves feasibility independently, even when a
    # deliberate tiny search budget expires before CP-SAT constructs a plan.
    witness = {str(i): i * 10 for i in range(30)}
    assert independent_feasible(project, witness)
    result = suggest(project, time_limit=1e-9)
    assert result.status == "time_limited"
    assert not result.placements and result.objective is None


