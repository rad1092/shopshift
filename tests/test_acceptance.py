def test_snapshot_overnight_day_selection_and_formula_html_escaping(tmp_path):
    start = parse_timestamp("2026-10-05T23:30Z", "UTC")
    project = Project(name="<script>bad</script>", horizon_start=start, horizon_end=start + 86400,
                      machines={"m": Resource("m", [Window(start, start + 86400)])}, operations={
                          "=HYPERLINK(1)": Operation("=HYPERLINK(1)", "@unsafe", "m", run=5400,
                                                     label="<img src=x onerror=bad>", due=start + 3600),
                          "unscheduled": Operation("unscheduled", "J", "m", run=60),
                      })
    project.scenario.placements["=HYPERLINK(1)"] = Placement(start, True)
    csv_path, html_path = tmp_path / "plan.csv", tmp_path / "plan.html"
    export_csv(project, csv_path, day="2026-10-06")
    export_html(project, html_path, day="2026-10-06")
    with csv_path.open(encoding="utf-8-sig", newline="") as handle:
        rows = list(csv.DictReader(handle))
    assert len(rows) == 2
    assert rows[0]["operation_id"] == "'=HYPERLINK(1)"
    assert rows[0]["job"] == "'@unsafe"
    assert rows[0]["late_seconds"] == "1800"
    assert rows[1]["status"] == "UNSCHEDULED"
    markup = html_path.read_text(encoding="utf-8")
    assert "<script>bad</script>" not in markup and "<img src=x" not in markup
    assert "&lt;script&gt;bad&lt;/script&gt;" in markup and "&lt;img src=x" in markup
    assert "DRAFT" in markup and "late" in markup and "unscheduled" in markup
