def test_dst_fold_offsets_represent_distinct_instants_and_roundtrip():
    first = parse_timestamp("2026-11-01T01:30-04:00", "America/New_York")
    second = parse_timestamp("2026-11-01T01:30-05:00", "America/New_York")
    assert second - first == 3600
    assert parse_timestamp(format_timestamp(first, "America/New_York"), "America/New_York") == first
    assert parse_timestamp(format_timestamp(second, "America/New_York"), "America/New_York") == second
    project = Project(timezone="America/New_York", horizon_start=first, horizon_end=second + 3600,
                      machines={"night": Resource("night", [Window(first, second + 3600)])},
                      operations={"a": Operation("a", "J", "night", run=5400)})
    project.scenario.placements["a"] = Placement(first, True)
    assert not [i for i in validate(project) if i.severity == "error"]
    assert suggest(project, time_limit=1).placements["a"].start == first


def test_overnight_weekday_shift_is_clipped_and_includes_saturday_morning():
    # Friday's shift remains available into Saturday, even though Saturday
    # itself does not start a weekday shift. The expected instants use stdlib.
    start = int(datetime(2026, 10, 9, 21, tzinfo=timezone.utc).timestamp())
    end = int(datetime(2026, 10, 10, 5, tzinfo=timezone.utc).timestamp())
    windows = working_windows(start, end, "Europe/Berlin", 22, 6)
    assert [(w.start, w.end) for w in windows] == [(start, end - 3600)]


def _write_csv(path, rows, headers=("Op", "Job", "Machine", "Run")):
    with path.open("w", newline="", encoding="utf-8-sig") as handle:
        writer = csv.writer(handle)
        writer.writerow(headers)
        writer.writerows(rows)


MAPPING = {"id": "Op", "job": "Job", "machine": "Machine", "run": "Run"}


def import_project():
    start = parse_timestamp("2026-10-05T08:00Z", "UTC")
    return Project(horizon_start=start, horizon_end=start + 7 * 86400)


def test_reimport_preserves_all_scenario_decisions_and_exposes_changed_duration(tmp_path):
    path = tmp_path / "erp.csv"
    _write_csv(path, [["a", "J", "mill", "60"], ["b", "J", "mill", "60"]])
    first = import_operations(import_project(), path, MAPPING).project
    start = first.horizon_start
    first.scenario.placements = {"a": Placement(start, True), "b": Placement(start + 3600)}
    first.scenarios["Alternative"] = Scenario("Alternative", {"a": Placement(start + 86400, True)})
    original = copy.deepcopy(first.to_dict())
    _write_csv(path, [["a", "J", "mill", "90"], ["c", "J", "lathe", "30"]])
    second = import_operations(first, path, first.mappings["__last__"])
    assert first.to_dict() == original
    assert second.added == ["c"] and second.updated == ["a"] and second.retained == ["b"]
    assert second.project.scenarios == first.scenarios
    assert second.project.operations["a"].duration == 5400
    assert second.project.operations["b"] == first.operations["b"]
    assert second.warnings and second.project.mappings["__last__"]["__duration_unit"] == "minutes"
    errors = [issue for issue in validate(second.project) if issue.severity == "error"]
    assert any({"a", "b"} <= set(issue.operation_ids) for issue in errors), errors
    assert second.project.scenario.placements["a"].locked


def test_reimport_retains_unmapped_fields_but_mapped_blanks_clear_them(tmp_path):
    path = tmp_path / "erp.csv"
    project = import_project()
    project.machines["m"] = Resource("m", [Window(project.horizon_start, project.horizon_end)])
    project.operations["a"] = Operation("a", "J", "m", setup=120, run=60, label="keep me",
                                        due=project.horizon_end, predecessors=["missing"])
    _write_csv(path, [["a", "J", "m", "1"]])
    minimal = import_operations(project, path, MAPPING).project.operations["a"]
    assert (minimal.setup, minimal.label, minimal.due, minimal.predecessors) == (
        120, "keep me", project.horizon_end, ["missing"])
    _write_csv(path, [["a", "J", "m", "1", "", "", ""]],
               (*MAPPING.values(), "Label", "Due", "Pred"))
    cleared = import_operations(project, path, dict(MAPPING, label="Label", due="Due", predecessors="Pred"))
    assert (cleared.project.operations["a"].label, cleared.project.operations["a"].due,
            cleared.project.operations["a"].predecessors) == ("", None, [])


